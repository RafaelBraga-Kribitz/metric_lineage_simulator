/**
 * The single headline result (ADR-0010 P5): rank the DTC seed's guesses by value of
 * information per unit of test cost. Pure and deterministic; rendered by the UI panel and
 * by `npm run example`.
 */
import type { BusinessModel, EvidenceGrade } from "../schema/types.js";
import { computeBaseline } from "./compute.js";
import { prioritize } from "./prioritize.js";
import { GUESS_CAVEAT, valueOfInformation } from "./valueOfInformation.js";

export const WORKED_EXAMPLE_SETTINGS = {
  runs: 20000,
  seed: 42,
  /** Planned decisions being considered: make pages 10% faster, lift email capture 10%. */
  plannedChanges: { page_load_speed: -0.1, email_capture_rate: 0.1 } as Record<string, number>,
  plannedChangePct: 0.1,
};

export interface WorkedExampleRow {
  rank: number | null;
  edge: string;
  grade: EvidenceGrade | "none";
  status: string;
  plannedChange: number | null;
  p10: number | null;
  p50: number | null;
  p90: number | null;
  voiScore: number | null;
  testCost: number;
  testCostAssumed: boolean;
  priorityScore: number | null;
  sources: string[];
}

export interface WorkedExample {
  question: string;
  target: string;
  baseline: number;
  settings: typeof WORKED_EXAMPLE_SETTINGS;
  rows: WorkedExampleRow[];
  decision: string;
  caveat: string;
}

const round = (v: number | null, d = 0) => (v === null ? null : Number(v.toFixed(d)));

function decisionFor(rows: WorkedExampleRow[], nameOf: (id: string) => string): string {
  const top = rows.find((r) => r.rank === 1);
  if (!top) return "No guess has a declared range on a path to the north star; add ranges before ranking.";
  const second = rows.find((r) => r.rank === 2);
  const ratio = second?.priorityScore ? (top.priorityScore as number) / second.priorityScore : null;
  const [child, parent] = top.edge.split(" → ");
  return (
    `Test ${nameOf(child ?? "")} → ${nameOf(parent ?? "")} first: its declared range blurs the planned outcome most per unit of test cost` +
    (ratio ? ` (${ratio.toFixed(1)}× the next guess).` : ".") +
    " This ranks what to learn, not what to do."
  );
}

export function buildWorkedExample(model: BusinessModel): WorkedExample {
  const s = WORKED_EXAMPLE_SETTINGS;
  const ranked = prioritize(
    valueOfInformation(model, { runs: s.runs, seed: s.seed, plannedChanges: s.plannedChanges, plannedChangePct: s.plannedChangePct }),
  );
  const nameOf = (id: string) => model.nodes.find((n) => n.id === id)?.name ?? id;
  const rows: WorkedExampleRow[] = ranked.map((r) => ({
    rank: r.rank,
    edge: `${r.edge.child} → ${r.edge.parent}`,
    grade: r.edge.evidence_grade ?? "none",
    status: r.status,
    plannedChange: r.status === "scored" ? (s.plannedChanges[r.edge.child] ?? s.plannedChangePct) : null,
    p10: round(r.p10),
    p50: round(r.p50),
    p90: round(r.p90),
    voiScore: round(r.voiScore),
    testCost: r.testCost,
    testCostAssumed: r.testCostAssumed,
    priorityScore: round(r.priorityScore),
    sources: (r.edge.evidence_source ?? []).map((src) => `${src.name} (${src.year}) ${src.url}`),
  }));
  const target = model.north_star_id;
  return {
    question: `Which guess about ${nameOf(target)} is most worth testing first?`,
    target,
    baseline: round(computeBaseline(model)[target] ?? 0) as number,
    settings: s,
    rows,
    decision: decisionFor(rows, nameOf),
    caveat: GUESS_CAVEAT,
  };
}

const eur = (v: number | null) => (v === null ? "—" : `€${Math.round(v).toLocaleString("en-US")}`);
const pct = (v: number | null) => (v === null ? "—" : `${v > 0 ? "+" : ""}${Math.round(v * 100)}%`);

export function renderWorkedExampleMarkdown(ex: WorkedExample): string {
  const lines = [
    "# Worked example: what to test first",
    "",
    `Generated by \`cd driver_tree_studio && npm run example\` (seed ${ex.settings.seed}, ${ex.settings.runs.toLocaleString("en-US")} draws per edge). Do not edit by hand.`,
    "",
    `**Question.** ${ex.question}`,
    "",
    `**Baseline.** ${ex.target} = ${eur(ex.baseline)} per period (ILLUSTRATIVE seed).`,
    "",
    "**Method.** For each modeled edge with a declared elasticity range, move its driver by the planned change, sample only that edge's elasticity, and measure the P90 − P10 spread of the north star (value of information). Divide by the declared relative test cost.",
    "",
    "| Rank | Edge | Grade | Planned change | P10 | P50 | P90 | VoI (P90−P10) | Test cost | Priority |",
    "|---|---|---|---|---|---|---|---|---|---|",
    ...ex.rows.map(
      (r) =>
        `| ${r.rank ?? "—"} | \`${r.edge}\` | ${r.grade} | ${pct(r.plannedChange)} | ${eur(r.p10)} | ${eur(r.p50)} | ${eur(r.p90)} | ${r.status === "scored" ? eur(r.voiScore) : r.status} | ${r.testCost}${r.testCostAssumed ? " (assumed)" : ""} | ${r.priorityScore === null ? "—" : r.priorityScore.toLocaleString("en-US")} |`,
    ),
    "",
    `**Decision.** ${ex.decision}`,
    "",
    "**Sources behind graded ranges.**",
    "",
    ...ex.rows.flatMap((r) => r.sources.map((src) => `- \`${r.edge}\`: ${src}`)),
    "",
    `> ${ex.caveat}`,
    "",
    "Test costs are declared relative effort units (illustrative). Hypothesized edges cannot be ranked until they get a range.",
    "",
  ];
  return lines.join("\n");
}
